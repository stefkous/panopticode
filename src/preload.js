const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('deck', {
  newSession: () => ipcRenderer.invoke('new-session'),
  listExternal: () => ipcRenderer.invoke('list-external'),
  importSession: (pid) => ipcRenderer.invoke('import-session', pid),
  onRequestImport: (fn) => ipcRenderer.on('request-import', fn),
  getAppearance: () => ipcRenderer.invoke('get-appearance'),
  setAppearance: (theme) => ipcRenderer.send('set-appearance', theme),
  onAppearance: (fn) => ipcRenderer.on('appearance', (_, theme) => fn(theme)),
  getTodos: () => ipcRenderer.invoke('todos-get'),
  saveTodos: (day) => ipcRenderer.send('todos-save', day),
  onTodos: (fn) => ipcRenderer.on('todos', (_, day) => fn(day)),
  rename: (id, name) => ipcRenderer.send('rename', id, name),
  showSessionMenu: (id) => ipcRenderer.send('session-menu', id),
  onRenameRequest: (fn) => ipcRenderer.on('rename-request', (_, id) => fn(id)),
  getColours: () => ipcRenderer.invoke('get-colours'),
  setColours: (colours) => ipcRenderer.send('set-colours', colours),
  closeForTodo: (id) => ipcRenderer.invoke('close-for-todo', id),
  reopenForTodo: (itemId, closedSession) => ipcRenderer.invoke('reopen-for-todo', itemId, closedSession),
  attach: (id, cols, rows) => ipcRenderer.send('attach', id, cols, rows),
  input: (id, data) => ipcRenderer.send('input', id, data),
  resize: (id, cols, rows) => ipcRenderer.send('resize', id, cols, rows),
  onSessions: (fn) => ipcRenderer.on('sessions', (_, sessions) => fn(sessions)),
  onData: (fn) => ipcRenderer.on('pty-data', (_, id, data) => fn(id, data)),
  onExit: (fn) => ipcRenderer.on('pty-exit', (_, id) => fn(id)),
  onRequestNewSession: (fn) => ipcRenderer.on('request-new-session', fn),
  onSelectIndex: (fn) => ipcRenderer.on('select-index', (_, i) => fn(i)),
});
